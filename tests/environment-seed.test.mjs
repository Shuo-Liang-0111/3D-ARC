// Exercise real movement and autonomous dynamics with no task-specific interactions.
const replayInputs = [
  Object.freeze({ turn: 0.25 }),
  Object.freeze({ move: 0.15 }),
  Object.freeze({ strafe: -0.1 }),
  Object.freeze({}),
];
const replaySteps = 400;
const delta = 0.05;

function advance(engine, state, step) {
  const input = replayInputs[Math.floor(step / 20) % replayInputs.length];
  state = engine.updateMovement(state, input, delta);
  return engine.updateEnvironment(state, delta);
}

function assertSameState(actual, expected, label) {
  // Avoid dumping whole game states when a reproducibility assertion fails.
  assert.ok(isDeepStrictEqual(actual, expected), label);
}

test("optional seed parsing accepts uint32 numbers and decimal strings, including zero", () => {
  for (const value of [undefined, null, ""]) assert.equal(parseSeed(value), null);
  for (const value of [0, -0, "0", "000"]) {
    assert.equal(parseSeed(value), 0);
    assert.equal(Object.is(parseSeed(value), -0), false);
  }
  for (const [input, expected] of [
    [1, 1], ["1", 1], ["00042", 42], [20261009, 20261009],
    ["20261009", 20261009], [4294967295, 4294967295], ["4294967295", 4294967295],
  ]) assert.equal(parseSeed(input), expected);
});

test("invalid seeds fail explicitly instead of coercing or wrapping", () => {
  const invalid = [
    -1, 4294967296, 1.5, NaN, Infinity, -Infinity,
    true, false, {}, [], [1], 1n, Symbol("seed"), () => 1,
    " ", " 0", "0 ", "+1", "-1", "1.0", "1e2", "0x1",
    "NaN", "Infinity", "null", "undefined", "4294967296",
  ];
  for (const value of invalid) assert.throws(() => parseSeed(value), RangeError);
  for (const value of [undefined, null, "", ...invalid]) {
    assert.throws(() => createSeededRandom(value), RangeError);
  }
  assert.throws(() => createSeededInitialState(rf01, "rf01", "bad"), RangeError);
});

test("arc-seed-v1 locks the Mulberry32 reference sequence", () => {
  assert.equal(SEED_PROTOCOL_VERSION, "arc-seed-v1");
  const random = createSeededRandom(1);
  // Canonical uint32 outputs, not values generated by the implementation under test.
  assert.deepEqual(
    Array.from({ length: 5 }, () => random() * 4294967296),
    [2693262067, 11749833, 2265367787, 4213581821, 4159151403],
  );
});

test("seeded random streams are independent, repeatable, and bounded", () => {
  for (const seed of [0, 1, 20261009, 4294967295]) {
    const left = createSeededRandom(seed);
    const right = createSeededRandom(String(seed));
    for (let index = 0; index < 256; index += 1) {
      const value = left();
      assert.equal(value, right());
      assert.ok(Number.isFinite(value) && value >= 0 && value < 1);
    }
  }
  const zero = createSeededRandom(0);
  const one = createSeededRandom(1);
  assert.notDeepEqual(
    Array.from({ length: 8 }, () => zero()),
    Array.from({ length: 8 }, () => one()),
  );
});

test("the advertised seeded policy has real-engine coverage; fixed ids stay fixed", () => {
  assert.equal(Object.isFrozen(SEEDED_LEVEL_IDS), true);
  assert.deepEqual([...SEEDED_LEVEL_IDS].sort(), scenarios.map(({ id }) => id).sort());
  for (const { id } of scenarios) assert.equal(getSeedPolicy(id), "seeded");
  // rf12-3 is the internal kitchen id, not the displayed RF-12-3 tennis label.
  for (const id of ["rf01", "rf02-2", "rf12-3", "unknown"]) {
    assert.equal(getSeedPolicy(id), "fixed");
  }
});

for (const scenario of scenarios) {
  test(scenario.id + ": the same seed reproduces real initial state and movement/time updates", () => {
    for (const seed of [0, 20261009, 4294967295]) {
      const leftEngine = scenario.engine();
      const rightEngine = scenario.engine();
      let left = createSeededInitialState(leftEngine, scenario.id, seed);
      let right = createSeededInitialState(rightEngine, scenario.id, String(seed));
      assertSameState(left, right, scenario.id + " initial seed=" + seed);
      for (let step = 0; step < replaySteps; step += 1) {
        left = advance(leftEngine, left, step);
        right = advance(rightEngine, right, step);
        assertSameState(left, right, scenario.id + " seed=" + seed + " step=" + step);
      }
    }
  });

  test(scenario.id + ": changing the seed changes actual random content, not only seed metadata", () => {
    const signatures = new Set();
    for (const seed of [0, 1, 2, 42, 4294967295]) {
      const engine = scenario.engine();
      let state = createSeededInitialState(engine, scenario.id, seed);
      const snapshots = [structuredClone(scenario.randomContent(state))];
      for (let step = 0; step < replaySteps; step += 1) {
        state = advance(engine, state, step);
        if (step % 40 === 39) snapshots.push(structuredClone(scenario.randomContent(state)));
      }
      signatures.add(JSON.stringify(snapshots));
    }
    assert.ok(signatures.size > 1, scenario.id + " has no observable random variation");
  });
}

test("RF01 real initialization and dynamics remain fixed for every supplied seed", () => {
  for (const seed of [undefined, null, "", 0, 1, 4294967295]) {
    let actual = createSeededInitialState(rf01, "rf01", seed);
    let expected = rf01.createInitialState();
    assertSameState(actual, expected, "RF01 unchanged initialization");
    for (let step = 0; step < 40; step += 1) {
      actual = advance(rf01, actual, step);
      expected = advance(rf01, expected, step);
    }
    assertSameState(actual, expected, "RF01 unchanged movement/time updates");
  }
});

test("RF09 office clock forwards seeded options to the real engine and resets its clock", () => {
  const engine = createOfficeEngine("rf09-3");
  let now = 1000;
  const clock = createOfficeClock(engine, () => now);
  const seed = 20261009;
  const expectedInitial = createSeededInitialState(engine, "rf09-3", seed);
  let actual = createSeededInitialState(clock, "rf09-3", seed);
  assertSameState(actual, expectedInitial, "office clock forwards options.random");

  let expected = engine.updateEnvironment(expectedInitial, 0.25);
  actual = clock.updateEnvironment(actual, 0.25);
  assertSameState(actual, expected, "office clock applies first fallback delta");
  for (const milliseconds of [50, 150, 900, 3000, 12000]) {
    now += milliseconds;
    expected = engine.updateEnvironment(expected, milliseconds / 1000);
    actual = clock.updateEnvironment(actual, 999);
    assertSameState(actual, expected, "office clock uses deterministic supplied time");
  }

  now += 60000;
  actual = createSeededInitialState(clock, "rf09-3", seed);
  assertSameState(actual, expectedInitial, "same seed resets the real office initial state");
  actual = clock.updateEnvironment(actual, 0.125);
  expected = engine.updateEnvironment(expectedInitial, 0.125);
  assertSameState(actual, expected, "reset discards the previous clock timestamp");
});

test("seeded autonomous transitions actually execute and reproduce", () => {
  const transitions = [
    {
      id: "rf02-3", engine: () => createArchiveEngine("rf02-3"),
      duration: (state) => state.incident.schedule[0].at + delta * 2,
      occurred: (state) => state.incident.drops > 0,
    },
    {
      id: "rf05-3", engine: () => createHotelEngine("rf05-3"),
      duration: () => 20,
      occurred: (state) => Object.values(state.items).some((item) => item.type === "tissue" && item.turns > 0),
    },
    {
      id: "rf06-3", engine: () => pestEngine,
      duration: () => 20,
      occurred: (state) => state.roaches.some((roach) => roach.decisions > 0),
    },
    {
      id: "rf07-3", engine: () => createSeriesEngine("rf07-3"),
      duration: (state) => state.alarm.triggerAt + delta * 2,
      occurred: (state) => state.alarm.status === "active",
    },
    {
      id: "rf09-3", engine: () => createOfficeEngine("rf09-3"),
      duration: (state) => state.phone.ringAt + delta * 2,
      occurred: (state) => state.phone.status === "ringing",
    },
    {
      id: "rf13-03", engine: () => createClinicEngine("high"),
      duration: (state) => state.nextWaveAt + delta * 2,
      occurred: (state) => state.requests.some((request) => request.issuedAt !== null),
    },
    {
      id: "rf14-3", engine: () => createCourtEngine("rf14-3"),
      duration: (state) => state.weather.remaining + delta * 2,
      occurred: (state) => state.weather.raining,
    },
  ];
  // RF07-2 randomizes the initial cabinet power configuration, not a timed event.
  for (const transition of transitions) {
    const leftEngine = transition.engine();
    const rightEngine = transition.engine();
    let left = createSeededInitialState(leftEngine, transition.id, 20261009);
    let right = createSeededInitialState(rightEngine, transition.id, 20261009);
    assert.equal(transition.occurred(left), false, transition.id + " starts before its event");
    const steps = Math.ceil(transition.duration(left) / delta);
    assert.ok(Number.isFinite(steps) && steps > 0 && steps < 72000);
    for (let step = 0; step < steps && !transition.occurred(left); step += 1) {
      left = leftEngine.updateEnvironment(left, delta);
      right = rightEngine.updateEnvironment(right, delta);
      assertSameState(left, right, transition.id + " autonomous event step=" + step);
    }
    assert.equal(transition.occurred(left), true, transition.id + " executes its autonomous event");
  }
});

test("omitting RF05 seed preserves the real legacy tissue initialization and movement", () => {
  const engine = createHotelEngine("rf05-3");
  for (const seed of [undefined, null, ""]) {
    let actual = createSeededInitialState(engine, "rf05-3", seed);
    let legacy = engine.createInitialState();
    assertSameState(actual, legacy, "legacy tissue initial state");
    for (let step = 0; step < replaySteps; step += 1) {
      actual = advance(engine, actual, step);
      legacy = advance(engine, legacy, step);
    }
    assertSameState(actual, legacy, "legacy tissue dynamics");
  }
});
