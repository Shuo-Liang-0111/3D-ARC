"""Seal widened RF04 door cuts with closed, solid jambs and lintel returns."""
import bpy,bmesh,json
from pathlib import Path
from mathutils import Vector
ROOT=Path('.')
OUT=ROOT/'public/local-assets/levels/rf04/architecture-v4'
OUT.mkdir(parents=True,exist_ok=True)
if (OUT/'home.glb').exists():raise RuntimeError('Do not overwrite a published asset version')
bpy.ops.wm.read_factory_settings(use_empty=True)
bpy.ops.import_scene.gltf(filepath=str(ROOT/'public/local-assets/levels/rf04/architecture-v3/home.glb'))
portals=json.loads((ROOT/'public/local-assets/levels/rf04/architecture-v3/manifest.json').read_text())['portals']
mat=bpy.data.materials.new('rf04-solid-doorframe-warm-ivory');mat.use_nodes=True
mat.diffuse_color=(.67,.61,.49,1)
shader=mat.node_tree.nodes.get('Principled BSDF');shader.inputs['Base Color'].default_value=(.67,.61,.49,1);shader.inputs['Roughness'].default_value=.64
records=[];parts=[]
def box(name,x,z,w,d,bottom,top):
 bpy.ops.mesh.primitive_cube_add(size=1,location=(x,-z,(bottom+top)/2))
 o=bpy.context.object;o.name=name;o.dimensions=(w,d,top-bottom)
 bpy.ops.object.transform_apply(location=False,rotation=False,scale=True)
 o.data.materials.append(mat)
 bevel=o.modifiers.new('Soft solid frame edges','BEVEL');bevel.width=.003;bevel.segments=2
 bpy.context.view_layer.objects.active=o;bpy.ops.object.modifier_apply(modifier=bevel.name)
 bm=bmesh.new();bm.from_mesh(o.data)
 assert all(e.is_manifold for e in bm.edges),name
 assert bm.calc_volume()>0,name
 bm.free()
 parts.append(dict(name=name,min=[x-w/2,bottom,z-d/2],max=[x+w/2,top,z+d/2]))
 return o
for p in portals:
 alongX=p['w']>p['d'];width=p['w'] if alongX else p['d'];depth=.37
 # Returns bridge both wall shells. 3.5cm inward overlap hides non-manifold cut edges.
 for sign in [-1,1]:
  center=sign*(width/2+.015)
  x=p['x']+(center if alongX else 0);z=p['z']+(0 if alongX else center)
  w,d=(.10,depth) if alongX else (depth,.10)
  name='rf04-door-'+p['id']+'-jamb-'+str(sign)
  box(name,x,z,w,d,0,2.29)
  records.append(dict(id=name,minX=x-w/2,maxX=x+w/2,minZ=z-d/2,maxZ=z+d/2))
 box('rf04-door-'+p['id']+'-head',p['x'],p['z'],width+.13 if alongX else depth,depth if alongX else width+.13,2.185,2.30)
 # Casing overlaps the wall surface on both room sides, hiding seams at oblique views.
 for face in [-1,1]:
  offset=face*.187
  for sign in [-1,1]:
   side=sign*(width/2+.025)
   x=p['x']+(side if alongX else offset);z=p['z']+(offset if alongX else side)
   box('rf04-door-'+p['id']+'-casing-'+str(face)+'-'+str(sign),x,z,.12 if alongX else .026,.026 if alongX else .12,0,2.33)
  box('rf04-door-'+p['id']+'-crown-'+str(face),p['x']+(0 if alongX else offset),p['z']+(offset if alongX else 0),width+.17 if alongX else .026,.026 if alongX else width+.17,2.185,2.33)
records=[dict(id=p['name'],minX=p['min'][0],maxX=p['max'][0],minZ=p['min'][2],maxZ=p['max'][2]) for p in parts if p['min'][1]==0]
report=dict(source='architecture-v3/home.glb',parts=parts,colliders=records,portals=[dict(**p,clearWidth=round((p['w'] if p['w']>p['d'] else p['d'])-.07,3),clearHeight=2.185)for p in portals])
(OUT/'doorframes.json').write_text(json.dumps(report,indent=2))
(ROOT/'game/levels/rf04/doorframe-layout.js').write_text('// Generated by tools/rf04-series/repair-doorframes.py; solid door jamb footprints.\nexport const DOORFRAME_COLLIDERS = '+json.dumps(records,separators=(',',':'))+';\n')
bpy.ops.export_scene.gltf(filepath=str(OUT/'home.glb'),export_format='GLB',export_draco_mesh_compression_enable=True,export_draco_mesh_compression_level=6,export_draco_position_quantization=16,export_draco_texcoord_quantization=12)
print('DOORFRAMES',len(parts),'closed manifold components',len(records),'collision jambs')
