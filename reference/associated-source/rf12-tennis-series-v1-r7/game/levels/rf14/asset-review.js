import * as THREE from "three";
import { GLTFLoader } from "three/addons/loaders/GLTFLoader.js";
import { OrbitControls } from "three/addons/controls/OrbitControls.js";
import { RoomEnvironment } from "three/addons/environments/RoomEnvironment.js";

const renderer = new THREE.WebGLRenderer({ antialias: true, preserveDrawingBuffer: true });
renderer.setSize(innerWidth, innerHeight);
renderer.toneMapping = THREE.ACESFilmicToneMapping;
renderer.toneMappingExposure = 1.3;
document.body.append(renderer.domElement);
const scene = new THREE.Scene(); scene.background = new THREE.Color('#d3d9d8');
const generator = new THREE.PMREMGenerator(renderer);
scene.environment = generator.fromScene(new RoomEnvironment(), 0.04).texture;
scene.add(new THREE.HemisphereLight(0xffffff, 0x727e75, 1.6));
const light = new THREE.DirectionalLight(0xfff4e4, 2.8); light.position.set(-4, 6, 4); scene.add(light);
const camera = new THREE.PerspectiveCamera(43, innerWidth / innerHeight, 0.01, 30);
const controls = new OrbitControls(camera, renderer.domElement);
const asset = new URLSearchParams(location.search).get('asset') || 'court-bench';
if (!['court-bench', 'tennis-bag', 'ball-hopper', 'umpire-chair', 'windscreen', 'plane-tree'].includes(asset)) throw new Error('Unknown asset');
const revision = new URLSearchParams(location.search).get('revision') || 'asset-review-v3';
if (!/^[a-z0-9.-]+$/.test(revision)) throw new Error('Invalid revision');
const model = (await new GLTFLoader().loadAsync(`/local-assets/levels/rf14/${revision}/${asset}.glb`)).scene;
scene.add(model);
const bounds = new THREE.Box3().setFromObject(model, true);
const size = bounds.getSize(new THREE.Vector3());
const center = bounds.getCenter(new THREE.Vector3());
const extent = Math.max(size.x, size.y, size.z);
camera.position.copy(center).add(new THREE.Vector3(extent * 1.1, extent * 0.65, extent * 1.3));
controls.target.copy(center); controls.update();
document.querySelector('#preview-status').textContent = `${asset} · ${size.toArray().map(value => value.toFixed(3)).join(' × ')} m`;
document.querySelector('#preview-status').dataset.ready = 'true';
renderer.setAnimationLoop(() => { controls.update(); renderer.render(scene, camera); });
