import assert from 'node:assert/strict';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { parseArgs } from 'node:util';

const { values } = parseArgs({ options: { source: { type: 'string' }, revision: { type: 'string' }, 'chair-x': { type: 'string' } } });
assert.match(values.source ?? '', /^[a-z0-9.-]+$/);
assert.match(values.revision ?? '', /^[a-z0-9.-]+$/);
const chairX = Number(values['chair-x']);
assert.ok(Number.isFinite(chairX));
const root = resolve('public/local-assets/levels/rf14');
const output = resolve(root, values.revision);
assert.ok(!existsSync(output), 'Use a new immutable asset revision');
cpSync(resolve(root, values.source), output, { recursive: true });
rmSync(`${output}/ball-hopper.glb`);
const bytes = readFileSync(`${output}/collision.glb`);
const jsonLength = bytes.readUInt32LE(12);
const document = JSON.parse(bytes.toString('utf8', 20, 20 + jsonLength));
assert.ok(!document.animations && !document.skins);
const removedIndex = document.nodes.findIndex(node => node.name === 'COLLIDER_ball-hopper');
assert.ok(removedIndex >= 0);
const chair = document.nodes.find(node => node.name === 'COLLIDER_umpire-chair');
assert.ok(chair?.translation && !chair.matrix);
chair.translation = [chairX, 1.15, 0];
const remap = indexes => indexes.filter(index => index !== removedIndex).map(index => index > removedIndex ? index - 1 : index);
document.nodes.splice(removedIndex, 1);
for (const node of document.nodes) if (node.children) node.children = remap(node.children);
for (const scene of document.scenes) scene.nodes = remap(scene.nodes);
const encoded = Buffer.from(JSON.stringify(document));
const padded = Buffer.concat([encoded, Buffer.alloc((4 - encoded.length % 4) % 4, 32)]);
const binaryChunk = bytes.subarray(20 + jsonLength);
const header = Buffer.alloc(20);
header.writeUInt32LE(0x46546c67, 0);
header.writeUInt32LE(2, 4);
header.writeUInt32LE(20 + padded.length + binaryChunk.length, 8);
header.writeUInt32LE(padded.length, 12);
header.writeUInt32LE(0x4e4f534a, 16);
writeFileSync(`${output}/collision.glb`, Buffer.concat([header, padded, binaryChunk]));
const manifestPath = `${output}/manifest.json`;
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8').replaceAll(values.source, values.revision));
manifest.interactables = manifest.interactables.filter(asset => asset.id !== 'ball-hopper');
delete manifest.hashes['ball-hopper.glb'];
manifest.hashes['collision.glb'] = createHash('sha256').update(readFileSync(`${output}/collision.glb`)).digest('hex');
manifest.layoutCorrection = { collectionCarts: 1, umpireChair: { position: [chairX, 0, 0], yaw: Math.PI / 2, facing: '+X, along the net toward court center' } };
writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
mkdirSync(`production/rf14/${values.revision}`, { recursive: true });
console.log(JSON.stringify({ revision: values.revision, ...manifest.layoutCorrection }));
